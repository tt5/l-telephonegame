def make_p4(pixels):
    """Build a P4 PBM byte string from a 2D list of 0/1."""
    buf = bytearray()
    buf += b"P4\n8 8\n"
    for row in pixels:
        byte = 0
        for j in range(8):
            byte = (byte << 1) | (row[j] & 1)
        buf.append(byte)
    return bytes(buf)
